#include "../libft.h"

int	ft_sqrt(int n)
{
	int	x;
	int	y;

	if (n < 0)
		return (-1);
	x = n;
	y = (x + 1) / 2;
	while (y < x)
	{
		x = y;
		y = (x + n / x) / 2;
	}
	return (x);
}
